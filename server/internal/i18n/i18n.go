var codeRe = regexp.MustCompile(`^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$`)

// ValidCode reports whether code looks like a BCP-47 language tag we accept.
func ValidCode(code string) bool { return codeRe.MatchString(code) && code != "zh" }

var placeholderRe = regexp.MustCompile(`\{\d+\}`)

func placeholders(s string) []string {
	p := placeholderRe.FindAllString(s, -1)
	sort.Strings(p)
	return p
}

// PlaceholderMismatches lists keys whose translation lost or invented {n} tokens.
func PlaceholderMismatches(strs map[string]string) []string {
	var bad []string
	for k, v := range strs {
		if v != "" && strings.Join(placeholders(k), ",") != strings.Join(placeholders(v), ",") {
			bad = append(bad, k)
		}
	}
	sort.Strings(bad)
	return bad
}

// Prompt is the instruction given to the AI (also shown in the admin panel so
// it can be pasted into any chat AI by hand).
func Prompt(targetName, targetCode string) string {
	return fmt.Sprintf(`You are translating the UI of a mobile VPN app called "环游" from Simplified Chinese into %s (%s).
Input: a JSON array of Chinese UI strings. Output: ONLY a JSON object mapping each original Chinese string (unchanged, as the key) to its translation.
Rules:
- Keep placeholders like {0} {1} exactly, same count; move them where the grammar needs.
- Keep VPN, ID, VP-, AI, ChatGPT, Claude, iOS, Android, Mbps, GB, MB, kbps, URLs, emoji and symbols (· ¥ → %%) as they are.
- Keep leading/trailing spaces and punctuation style natural for the language.
- Short, natural app wording (buttons are 1–3 words). Address the user informally if the language allows.
- The app name "环游" may be written as "Huanyou".`, targetName, targetCode)
}

// AIConfig is an OpenAI-compatible chat completions endpoint.
type AIConfig struct {
	BaseURL string `json:"base_url"` // e.g. https://api.openai.com/v1
	APIKey  string `json:"api_key"`
	Model   string `json:"model"` // e.g. gpt-4o-mini
}

func (c AIConfig) Ready() bool { return c.BaseURL != "" && c.APIKey != "" && c.Model != "" }

var httpClient = &http.Client{Timeout: 90 * time.Second}

// Translate sends one batch of keys and returns the translations it got back.
// Keys missing from the reply are simply absent.
func Translate(ctx context.Context, cfg AIConfig, targetName, targetCode string, keys []string) (map[string]string, error) {
	if !cfg.Ready() {
		return nil, errors.New("未配置 AI 翻译接口")
	}
	in, _ := json.Marshal(keys)
	body, _ := json.Marshal(map[string]any{
		"model":       cfg.Model,
		"temperature": 0.2,
		"messages": []map[string]string{
			{"role": "system", "content": Prompt(targetName, targetCode)},
			{"role": "user", "content": string(in)},
		},
		"response_format": map[string]string{"type": "json_object"},
	})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, strings.TrimRight(cfg.BaseURL, "/")+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+cfg.APIKey)
	resp, err := httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("AI 接口请求失败：%w", err)
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("AI 接口返回 %d：%s", resp.StatusCode, truncate(string(raw), 300))
	}
	var out struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(raw, &out); err != nil || len(out.Choices) == 0 {
		return nil, fmt.Errorf("AI 接口返回格式不正确：%s", truncate(string(raw), 300))
	}
	return ParsePack(out.Choices[0].Message.Content)
}

// ParsePack reads a {"中文": "translation"} object, tolerating a ```json fence
// or extra text around it (as chat AIs often add).
func ParsePack(s string) (map[string]string, error) {
	s = strings.TrimSpace(s)
	if i, j := strings.Index(s, "{"), strings.LastIndex(s, "}"); i >= 0 && j > i {
		s = s[i : j+1]
	}
	var m map[string]any
	if err := json.Unmarshal([]byte(s), &m); err != nil {
		return nil, fmt.Errorf("不是有效的 JSON 对象：%v", err)
	}
	out := make(map[string]string, len(m))
	for k, v := range m {
		if str, ok := v.(string); ok {
			out[k] = str
		}
	}
	return out, nil
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

// Chat sends one system + user message to the configured OpenAI-compatible
// API and returns the reply text (used for log analysis in the admin panel).
func Chat(ctx context.Context, cfg AIConfig, system, user string) (string, error) {
	if !cfg.Ready() {
		return "", errors.New("未配置 AI 接口")
	}
	body, _ := json.Marshal(map[string]any{
		"model":       cfg.Model,
		"temperature": 0.2,
		"messages": []map[string]string{
			{"role": "system", "content": system},
			{"role": "user", "content": user},
		},
	})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, strings.TrimRight(cfg.BaseURL, "/")+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+cfg.APIKey)
	resp, err := httpClient.Do(req)
	if err != nil {
		return "", fmt.Errorf("AI 接口请求失败：%w", err)
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("AI 接口返回 %d：%s", resp.StatusCode, truncate(string(raw), 300))
	}
	var out struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(raw, &out); err != nil || len(out.Choices) == 0 {
		return "", fmt.Errorf("AI 接口返回格式不正确：%s", truncate(string(raw), 300))
	}
	return strings.TrimSpace(out.Choices[0].Message.Content), nil
}
