//go:embed base.json
var baseJSON []byte

var baseKeys = func() []string {
	var k []string
	if err := json.Unmarshal(baseJSON, &k); err != nil {
		panic("i18n: bad base.json: " + err.Error())
	}
	return k
}()

// Base returns every translatable string (generated by scripts/i18n-extract.py).
func Base() []string { return append([]string(nil), baseKeys...) }

